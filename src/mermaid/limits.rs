//! Защитные лимиты рендеринга диаграмм (ТЗ §15).

/// Максимальный размер исходника одной диаграммы.
pub const MAX_SOURCE_BYTES: usize = 64 * 1024;

/// Максимальный размер SVG одной диаграммы — выхода рендерера.
///
/// Ресурс затем проходит общие лимиты изображений (ТЗ §40), но отдельный
/// потолок нужен раньше: он ограничивает то, что вообще попадает в память
/// из-за одного блока Markdown.
pub const MAX_SVG_BYTES: usize = 16 * 1024 * 1024;
